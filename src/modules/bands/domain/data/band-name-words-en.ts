import type { EnglishNoun } from "@/common/language/lexicon";
import type { EnglishLexicon } from "@/modules/bands/domain/generation/band-name.lexicon";

/**
 * Builds a countable English noun. The plural defaults to `sg + "s"`; irregular
 * plurals ("Wolves", "Colossi") must be passed explicitly.
 *
 * @param sg - Singular form.
 * @param pl - Plural form.
 * @returns The noun entry.
 */
function noun(sg: string, pl = `${sg}s`): EnglishNoun {
  return { sg, pl };
}

/**
 * Builds an English mass noun (no plural, no "a/an").
 *
 * @param sg - The only form.
 * @returns The noun entry.
 */
function mass(sg: string): EnglishNoun {
  return { sg, pl: null };
}

/**
 * Builds an English proper name (no plural, no article).
 *
 * @param sg - The name.
 * @returns The noun entry.
 */
function proper(sg: string): EnglishNoun {
  return { sg, pl: null, proper: true };
}

